"""Sync the FigCraft-exported palette into DocFX and fingerprint theme assets."""
from pathlib import Path
import hashlib,json,re

ROOT=Path(__file__).resolve().parents[2]
palette=ROOT/'docs/portfolio/tokens.css'
source=ROOT/'artifacts/portfolio-roundtrip/figcraft-variables.css'
assert palette.read_bytes()==source.read_bytes(), 'Palette must remain an actual FigCraft export'
public=ROOT/'docs/template/public'
(public/'theme-tokens.css').write_bytes(palette.read_bytes())
colors=dict(re.findall(r'--([a-z]+):\s*(#[0-9A-Fa-f]+)',palette.read_text(encoding='utf-8')))
assert len(colors)==6
options={'defaultTheme':'light','mermaid':{'securityLevel':'strict','theme':'base','themeVariables':{
    'fontFamily':'Microsoft YaHei, Arial, sans-serif','primaryColor':colors['white'],
    'primaryTextColor':colors['ink'],'primaryBorderColor':colors['muted'],
    'lineColor':colors['ink'],'secondaryColor':colors['paper'],'tertiaryColor':colors['yellow']},
    'flowchart':{'useMaxWidth':True,'htmlLabels':False,'curve':'linear'},'sequence':{'useMaxWidth':True,'wrap':True}}}
(public/'main.js').write_text('// Generated by tools/docs/sync_theme.py from the native FigCraft palette.\nexport default '+json.dumps(options,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
paths=['docs/toc.yml','docs/development/toc.yml','docs/template/public/theme-tokens.css','docs/template/public/main.css','docs/template/public/main.js','docs/template/public/reading.js','docs/template/layout/_master.tmpl']
if (public/'theme-type.css').exists(): paths.append('docs/template/public/theme-type.css')
hashes={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in paths}
revision=hashlib.sha256(json.dumps(hashes,sort_keys=True).encode()).hexdigest()[:12]
p=ROOT/'docs/docfx.json';config=json.loads(p.read_text(encoding='utf-8'))
config['build']['postProcessors']=['ExtractSearchIndex']
config['build']['globalMetadata'].update({'_disableToc':False,'_enableSearch':True,'_themeRevision':revision,
    '_appFooter':'<span class="ld-footer-word">LAUNCHDESK.NEXT / KNOWLEDGE SYSTEM</span><span class="ld-footer-note">功能事实 · 源码路径 · 验证证据　/　DocFX</span>'})
p.write_text(json.dumps(config,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
out=ROOT/'artifacts/docfx-theme';out.mkdir(exist_ok=True)
native=ROOT/'docs/portfolio/design/launchdesk-portfolio.figcraft'
(out/'theme-source.json').write_text(json.dumps({'date':'2026-10-31','revision':revision,
    'paletteSource':'docs/portfolio/tokens.css','paletteSha256':hashlib.sha256(palette.read_bytes()).hexdigest(),
    'nativeFigCraftSha256':hashlib.sha256(native.read_bytes()).hexdigest(),'docfxNativeSha256':hashlib.sha256((ROOT/'docs/design/docfx-reading-theme.figcraft').read_bytes()).hexdigest() if (ROOT/'docs/design/docfx-reading-theme.figcraft').exists() else None,'colors':colors,'themeFiles':hashes,
    'scope':'DocFX reading shell and styles; not product UI. Layout verified on rendered HTML; palette comes from native export.'},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('DocFX theme revision',revision)
