using System;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using System.Xml.Schema;

namespace Core30.Requests;

public sealed partial class RequestGenerator
{
    private static string GenerateBinding(XElement binding, string type, XmlSchemaElement element)
    {
        if ((string?)binding.Attribute("path") is { } path)
            foreach (var step in path.Split('/'))
                element = FindChild(binding, step, ChildElements((element.ElementSchemaType as XmlSchemaComplexType)?.ContentTypeParticle));

        var fields = binding.Elements().Select(field => ReadField(field, element)).ToArray();
        if (fields.Length == 0 || fields.Select(field => field.Property).Distinct(StringComparer.Ordinal).Count() != fields.Length)
            throw Invalid(binding, "A binding must declare at least one field and no duplicate properties.");
        var outputMode = (string?)binding.Attribute("output");
        if (outputMode is not (null or "attributes"))
            throw Invalid(binding, "A binding's output must be 'attributes' when specified.");

        var output = new StringBuilder("""
            // <auto-generated/>
            #nullable enable
            using System.Collections.Generic;
            using System.Text.Json.Nodes;
            using Core30.Core;

            namespace Core30.Generated;

            """);
        output.Append('\n').AppendLine(GeneratedCode)
            .Append("public sealed record ").Append(type).AppendLine("(")
            .Append("    ").Append(string.Join(",\n    ", fields.Select(field => field.Type + " " + field.Property))).AppendLine(")")
            .AppendLine("{")
            .AppendLine("    /// <summary>Reads the attribute values after request schema validation.</summary>")
            .Append("    public static ").Append(type).AppendLine(" ReadValidated(CoreData source) => new(")
            .Append("        ").Append(string.Join(",\n        ", fields.Select(field => field.Read))).AppendLine(");");

        if (outputMode == "attributes")
        {
            output.AppendLine().AppendLine("    public IEnumerable<CoreField> ToFields()").AppendLine("    {");
            foreach (var field in fields)
            {
                if (field.Optional)
                    output.Append("        if (").Append(field.Property).AppendLine(" is not null)");
                output.Append(field.Optional ? "            " : "        ").Append("yield return new(")
                    .Append(field.Key).Append(", ").Append(field.Property).AppendLine(");");
            }
            output.AppendLine("    }");
        }
        if (fields.Any(field => field.Stored))
        {
            output.AppendLine().AppendLine("    public void WriteStoredFields(JsonObject target)").AppendLine("    {");
            foreach (var field in fields.Where(field => field.Stored))
            {
                if (field.Optional)
                    output.Append("        if (").Append(field.Property).AppendLine(" is null)")
                        .Append("            target.Remove(").Append(field.Key).AppendLine(");").AppendLine("        else");
                output.Append(field.Optional ? "            " : "        ").Append("target[")
                    .Append(field.Key).Append("] = ").Append(field.Property).AppendLine(";");
            }
            output.AppendLine("    }");
        }
        return output.AppendLine("}").ToString();
    }

    private static (string Key, string Property, string Type, string Read, bool Optional, bool Stored) ReadField(
        XElement field, XmlSchemaElement element)
    {
        if ((field.Name != "field" && field.Name != "stored") || field.HasElements || !string.IsNullOrWhiteSpace(field.Value))
            throw Invalid(field, "A field binding accepts only empty <field> and <stored> elements.");
        var name = Name(field, "name", requireUppercase: false);
        var schemaType = element.ElementSchemaType as XmlSchemaComplexType;
        if (FindAttribute(schemaType, new XmlQualifiedName(name)) is not { } attribute)
            throw Invalid(field, $"'{name}' is not an attribute on <{element.QualifiedName.Name}>.");
        var type = attribute.AttributeSchemaType?.Datatype?.TypeCode switch
        {
            XmlTypeCode.String or XmlTypeCode.NormalizedString or XmlTypeCode.Token => "string",
            XmlTypeCode.Int or XmlTypeCode.Short or XmlTypeCode.UnsignedShort or XmlTypeCode.Byte or XmlTypeCode.UnsignedByte => "int",
            XmlTypeCode.Boolean => "bool",
            _ => throw Invalid(field, $"'{name}' does not have a supported binding datatype.")
        };
        var optional = attribute.Use != XmlSchemaUse.Required;
        var key = Literal(name);
        var property = char.ToUpperInvariant(name[0]) + name.Substring(1);
        var lookup = $"source.Field({key})";
        var read = type == "string" && !optional ? lookup + "!.Value" :
            (optional ? $"({type}?){lookup}" : $"({type}){lookup}!");
        return (key, property, optional ? type + "?" : type, read, optional, field.Name == "stored");
    }
}
